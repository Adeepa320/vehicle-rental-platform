/**
 * Regenerates `src/auth/common-passwords.ts` (OWASP ASVS 5.0.0 V6.2.4: new
 * passwords must be checked against at least the 3,000 most common passwords
 * **that satisfy the password policy**). The input is a frequency-ordered
 * password list; entries shorter than `PASSWORD_MIN_LENGTH` or longer than
 * `PASSWORD_MAX_LENGTH` are skipped, so the output is the top 3,000 that a
 * 10–128 character rule would otherwise let through.
 *
 *   pnpm --filter @vrp/contracts exec tsx scripts/generate-common-passwords.ts <list.txt> [--source "<label>"]
 *
 * Source used for the committed file: SecLists
 * `Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt`
 * (Daniel Miessler, MIT licence; frequency-ordered). Nothing is downloaded by
 * this script: pass the file you retrieved and record the date in `--source`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { PASSWORD_MAX_LENGTH, PASSWORD_MIN_LENGTH } from '../src/auth/auth';

const TARGET = 3000;

function parseArgs(argv: string[]): { input: string; source: string } {
  let input: string | undefined;
  let source = 'SecLists xato-net-10-million-passwords-1000000.txt (MIT)';
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--source') source = argv[++i] ?? source;
    else if (arg?.startsWith('--')) throw new Error(`Unknown argument ${arg}`);
    else input = arg;
  }
  if (!input)
    throw new Error('usage: generate-common-passwords.ts <list.txt> [--source "<label>"]');
  return { input, source };
}

function main(): void {
  const { input, source } = parseArgs(process.argv.slice(2));
  const lines = readFileSync(input, 'utf8').split(/\r?\n/);
  const seen = new Set<string>();
  const selected: string[] = [];
  for (const raw of lines) {
    const value = raw.trim().toLowerCase();
    if (value.length < PASSWORD_MIN_LENGTH || value.length > PASSWORD_MAX_LENGTH) continue;
    if (seen.has(value)) continue;
    seen.add(value);
    selected.push(value);
    if (selected.length === TARGET) break;
  }
  if (selected.length < TARGET) {
    throw new Error(`only ${selected.length} eligible passwords in ${input}; need ${TARGET}`);
  }

  const header = `/**
 * The ${TARGET.toLocaleString('en-US')} most common passwords that satisfy the password policy
 * (${PASSWORD_MIN_LENGTH}–${PASSWORD_MAX_LENGTH} characters), lower-cased and de-duplicated, taken in frequency
 * order from
 * ${source}.
 * OWASP ASVS 5.0.0 V6.2.4 (Level 1) requires checking new passwords against at
 * least the top 3,000 that match the policy; the API checks the lower-cased
 * password and refuses a match. Generated by
 * \`scripts/generate-common-passwords.ts\` — do not edit by hand.
 */
export const COMMON_PASSWORDS_TOP_3000: readonly string[] = [
`;
  const body = selected.map((value) => `  ${JSON.stringify(value)},\n`).join('');
  const footer = `];

const lookup = new Set(COMMON_PASSWORDS_TOP_3000);

/** True when the password (case-insensitively) is one of the ${TARGET.toLocaleString('en-US')} most common policy-compliant passwords. */
export function isCommonPassword(password: string): boolean {
  return lookup.has(password.trim().toLowerCase());
}
`;
  const target = resolve(__dirname, '../src/auth/common-passwords.ts');
  writeFileSync(target, header + body + footer);
  console.warn(`wrote ${selected.length} entries to ${target}`);
}

main();
